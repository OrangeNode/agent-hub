package com.agenthub.ai.model;

import static org.assertj.core.api.Assertions.assertThat;

import com.agenthub.ai.model.dto.AiModelItem;
import com.agenthub.ai.model.dto.AiModelRuntimeConfig;
import com.agenthub.ai.model.mapper.AiModelMapper;
import java.sql.Connection;
import java.sql.Statement;
import java.util.List;
import javax.sql.DataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mybatis.spring.annotation.MapperScan;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.SpringBootConfiguration;
import org.springframework.boot.autoconfigure.EnableAutoConfiguration;
import org.springframework.boot.test.context.SpringBootTest;

@SpringBootTest(
        classes = AiModelMapperIntegrationTest.TestApplication.class,
        properties = {
                "spring.datasource.url=jdbc:h2:mem:ai_model_mapper;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1;INIT=CREATE DOMAIN IF NOT EXISTS TIMESTAMPTZ AS TIMESTAMP WITH TIME ZONE",
                "spring.datasource.username=sa",
                "spring.datasource.password=",
                "spring.datasource.driver-class-name=org.h2.Driver"
        }
)
class AiModelMapperIntegrationTest {

    @Autowired
    private AiModelMapper mapper;

    @Autowired
    private DataSource dataSource;

    @BeforeEach
    void resetSchema() throws Exception {
        try (Connection connection = dataSource.getConnection();
             Statement statement = connection.createStatement()) {
            statement.execute("drop table if exists ai_model");
            statement.execute("drop table if exists ai_provider");
            statement.execute("""
                    create table ai_provider (
                        id bigint generated by default as identity primary key,
                        code varchar(64) not null,
                        name varchar(128) not null,
                        provider_type varchar(32) not null,
                        protocol_type varchar(64) not null,
                        base_url varchar(512) not null,
                        api_key_cipher text,
                        auth_type varchar(64) not null,
                        api_version varchar(64),
                        extra_headers text,
                        extra_body text,
                        enabled boolean not null default true,
                        sort int not null default 0,
                        constraint uk_ai_provider_code unique (code)
                    )
                    """);
            statement.execute("""
                    create table ai_model (
                        id bigint generated by default as identity primary key,
                        provider_id bigint not null,
                        model_code varchar(128) not null,
                        display_name varchar(128) not null,
                        capability_type varchar(64) not null,
                        stream_supported boolean not null default true,
                        reasoning_supported boolean not null default false,
                        context_window int,
                        max_output_tokens int,
                        default_model boolean not null default false,
                        enabled boolean not null default true,
                        sort int not null default 0,
                        constraint uk_ai_model_provider_code unique (provider_id, model_code),
                        constraint fk_ai_model_provider foreign key (provider_id) references ai_provider (id)
                    )
                    """);
        }
    }

    @Test
    void shouldSelectOnlyEnabledModelsFromEnabledProviders() throws Exception {
        seedProvidersAndModels();

        List<AiModelItem> items = mapper.selectAvailableItems();

        assertThat(items)
                .extracting(AiModelItem::modelCode)
                .containsExactly("enabled-model");
    }

    @Test
    void shouldMapJoinedModelAndRuntimeConfigAliases() throws Exception {
        seedProvidersAndModels();

        AiModelItem item = mapper.selectJoinedById(1L);
        AiModelRuntimeConfig config = mapper.selectRuntimeConfigById(1L);

        assertThat(item.providerCode()).isEqualTo("enabled-provider");
        assertThat(item.providerName()).isEqualTo("启用供应商");
        assertThat(item.modelCode()).isEqualTo("enabled-model");
        assertThat(config.providerType()).isEqualTo("LLM");
        assertThat(config.protocolType()).isEqualTo("OPENAI");
        assertThat(config.baseUrl()).isEqualTo("https://api.example.com/v1");
        assertThat(config.apiKeyCipher()).isEqualTo("cipher-enabled");
        assertThat(config.extraHeaders()).isEqualTo("{\"h\":\"v\"}");
        assertThat(config.extraBody()).isEqualTo("{\"b\":\"v\"}");
        assertThat(config.enabled()).isTrue();
        assertThat(config.providerEnabled()).isTrue();
    }

    private void seedProvidersAndModels() throws Exception {
        try (Connection connection = dataSource.getConnection();
             Statement statement = connection.createStatement()) {
            statement.execute("""
                    insert into ai_provider
                        (id, code, name, provider_type, protocol_type, base_url, api_key_cipher, auth_type, api_version, extra_headers, extra_body, enabled, sort)
                    values
                        (1, 'enabled-provider', '启用供应商', 'LLM', 'OPENAI', 'https://api.example.com/v1', 'cipher-enabled', 'BEARER', 'v1', '{"h":"v"}', '{"b":"v"}', true, 1),
                        (2, 'disabled-provider', '禁用供应商', 'LLM', 'OPENAI', 'https://api.disabled.com/v1', 'cipher-disabled', 'BEARER', 'v1', '{}', '{}', false, 2)
                    """);
            statement.execute("""
                    insert into ai_model
                        (id, provider_id, model_code, display_name, capability_type, stream_supported, reasoning_supported, context_window, max_output_tokens, default_model, enabled, sort)
                    values
                        (1, 1, 'enabled-model', '启用模型', 'CHAT', true, false, 128000, 4096, true, true, 1),
                        (2, 1, 'disabled-model', '禁用模型', 'CHAT', true, false, 64000, 2048, false, false, 2),
                        (3, 2, 'disabled-provider-model', '禁用供应商模型', 'CHAT', true, false, 32000, 1024, false, true, 3)
                    """);
        }
    }

    @SpringBootConfiguration
    @EnableAutoConfiguration
    @MapperScan("com.agenthub.ai.model.mapper")
    static class TestApplication {
    }
}
