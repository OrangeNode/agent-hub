CREATE TABLE operation_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trace_id VARCHAR(64),
    user_id BIGINT,
    username VARCHAR(64),
    module VARCHAR(64) NOT NULL,
    action VARCHAR(128) NOT NULL,
    target_type VARCHAR(64),
    target_id VARCHAR(256),
    operation_type VARCHAR(64) NOT NULL DEFAULT 'MANAGE',
    reason VARCHAR(512),
    request_method VARCHAR(16),
    request_uri VARCHAR(512),
    client_ip VARCHAR(64),
    user_agent VARCHAR(512),
    params_json TEXT,
    result_json TEXT,
    status VARCHAR(32) NOT NULL,
    error_code VARCHAR(64),
    error_message TEXT,
    duration_ms BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_operation_log_created_at ON operation_log (created_at DESC);
CREATE INDEX idx_operation_log_user_created_at ON operation_log (user_id, created_at DESC);
CREATE INDEX idx_operation_log_module_action ON operation_log (module, action);
CREATE INDEX idx_operation_log_status_created_at ON operation_log (status, created_at DESC);
CREATE INDEX idx_operation_log_target_created_at ON operation_log (target_type, target_id, created_at DESC);

