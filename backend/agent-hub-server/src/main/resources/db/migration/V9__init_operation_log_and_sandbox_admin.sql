INSERT INTO sys_role_menu (role_id, menu_id, created_by, updated_by)
SELECT sr.id, sm.id, 1, 1
FROM sys_role sr
JOIN (
    SELECT root.id
    FROM sys_menu root
    WHERE root.parent_id = 0
        AND root.name = 'sandbox'
    UNION ALL
    SELECT child.id
    FROM sys_menu root
    JOIN sys_menu child ON child.parent_id = root.id
    WHERE root.parent_id = 0
        AND root.name = 'sandbox'
        AND child.name = 'sandboxMonitor'
    UNION ALL
    SELECT button.id
    FROM sys_menu root
    JOIN sys_menu monitor ON monitor.parent_id = root.id
    JOIN sys_menu button ON button.parent_id = monitor.id
    WHERE root.parent_id = 0
        AND root.name = 'sandbox'
        AND monitor.name = 'sandboxMonitor'
        AND button.name IN ('sandboxRuntimeReap', 'sandboxSessionClose', 'sandboxRuntimeCleanup', 'sandboxRuntimeKill')
    UNION ALL
    SELECT operation_logs.id
    FROM sys_menu system_root
    JOIN sys_menu operation_logs ON operation_logs.parent_id = system_root.id
    WHERE system_root.parent_id = 0
        AND system_root.name = 'system'
        AND operation_logs.name = 'operationLogs'
) sm ON 1 = 1
WHERE sr.code = 'ADMIN'
    AND NOT EXISTS (
        SELECT 1
        FROM sys_role_menu srm
        WHERE srm.role_id = sr.id
            AND srm.menu_id = sm.id
    );
