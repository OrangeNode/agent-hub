INSERT INTO sys_menu (parent_id, name, title, path, component, icon, permission, menu_type, visible, sort, created_by, updated_by)
SELECT parent.id, 'agentList', 'Agent 列表', '/agent/list', 'agent/list/index', 'RobotOutlined', 'agent:list', 'MENU', TRUE, 1, 1, 1
FROM sys_menu parent
WHERE parent.parent_id = 0
    AND parent.name = 'agent'
    AND NOT EXISTS (
        SELECT 1
        FROM sys_menu child
        WHERE child.parent_id = parent.id
            AND child.name = 'agentList'
    );

INSERT INTO sys_role_menu (role_id, menu_id, created_by, updated_by)
SELECT sr.id, sm.id, 1, 1
FROM sys_role sr
JOIN (
    SELECT root.id
    FROM sys_menu root
    WHERE root.parent_id = 0
        AND root.name = 'agent'
    UNION ALL
    SELECT child.id
    FROM sys_menu root
    JOIN sys_menu child ON child.parent_id = root.id
    WHERE root.parent_id = 0
        AND root.name = 'agent'
        AND child.name = 'agentList'
) sm ON 1 = 1
WHERE sr.code = 'ADMIN'
    AND NOT EXISTS (
        SELECT 1
        FROM sys_role_menu srm
        WHERE srm.role_id = sr.id
            AND srm.menu_id = sm.id
    );
