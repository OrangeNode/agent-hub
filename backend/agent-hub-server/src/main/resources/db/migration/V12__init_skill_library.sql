CREATE TABLE skill_package (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_key VARCHAR(128) NOT NULL,
    name VARCHAR(128) NOT NULL,
    description VARCHAR(512),
    original_filename VARCHAR(256) NOT NULL,
    bucket_name VARCHAR(128) NOT NULL,
    object_key VARCHAR(512) NOT NULL,
    content_type VARCHAR(128) NOT NULL,
    file_size BIGINT NOT NULL DEFAULT 0,
    skill_md_path VARCHAR(512) NOT NULL,
    skill_md_content TEXT NOT NULL,
    file_count INT NOT NULL DEFAULT 0,
    created_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_skill_package_key UNIQUE (skill_key),
    CONSTRAINT uk_skill_package_name UNIQUE (name)
);

CREATE INDEX idx_skill_package_updated_at
    ON skill_package (updated_at DESC, id DESC);

CREATE TABLE skill_import (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    original_filename VARCHAR(256) NOT NULL,
    bucket_name VARCHAR(128) NOT NULL,
    object_key VARCHAR(512) NOT NULL,
    content_type VARCHAR(128) NOT NULL,
    file_size BIGINT NOT NULL DEFAULT 0,
    status VARCHAR(32) NOT NULL,
    parsed_name VARCHAR(128),
    parsed_description VARCHAR(512),
    root_dir VARCHAR(512),
    skill_md_path VARCHAR(512),
    skill_md_content TEXT,
    file_count INT NOT NULL DEFAULT 0,
    manifest_json TEXT,
    error_message TEXT,
    created_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_skill_import_status_created_at
    ON skill_import (status, created_at DESC, id DESC);

CREATE TABLE skill_file_manifest (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id BIGINT NOT NULL,
    relative_path VARCHAR(1024) NOT NULL,
    directory BOOLEAN NOT NULL DEFAULT FALSE,
    size_bytes BIGINT NOT NULL DEFAULT 0,
    sha256 VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_skill_file_package FOREIGN KEY (skill_id) REFERENCES skill_package (id) ON DELETE CASCADE,
    CONSTRAINT uk_skill_file_package_path UNIQUE (skill_id, relative_path)
);

CREATE INDEX idx_skill_file_package
    ON skill_file_manifest (skill_id, relative_path);

CREATE TABLE agent_skill_binding (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id BIGINT NOT NULL,
    skill_id BIGINT NOT NULL,
    sort INT NOT NULL DEFAULT 0,
    created_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_agent_skill_agent FOREIGN KEY (agent_id) REFERENCES agent_config (id) ON DELETE CASCADE,
    CONSTRAINT fk_agent_skill_package FOREIGN KEY (skill_id) REFERENCES skill_package (id) ON DELETE CASCADE,
    CONSTRAINT uk_agent_skill_binding UNIQUE (agent_id, skill_id)
);

CREATE INDEX idx_agent_skill_agent_sort
    ON agent_skill_binding (agent_id, sort, id);

