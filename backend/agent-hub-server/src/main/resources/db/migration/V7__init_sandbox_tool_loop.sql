CREATE TABLE sandbox_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    sandbox_session_id VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'READY',
    image VARCHAR(128) NOT NULL DEFAULT 'minimal',
    vcpu INT NOT NULL DEFAULT 1,
    memory_mb INT NOT NULL DEFAULT 1024,
    disk_gb INT NOT NULL DEFAULT 5,
    last_active_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ,
    CONSTRAINT uk_sandbox_session_runtime_id UNIQUE (sandbox_session_id),
    CONSTRAINT fk_sandbox_session_conversation FOREIGN KEY (conversation_id) REFERENCES chat_conversation (id)
);

CREATE INDEX idx_sandbox_session_conversation
    ON sandbox_session (conversation_id);

CREATE INDEX idx_sandbox_session_user_status
    ON sandbox_session (user_id, status);

CREATE TABLE sandbox_execution (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sandbox_session_id BIGINT NOT NULL,
    conversation_id BIGINT NOT NULL,
    message_id BIGINT,
    tool_call_id VARCHAR(128),
    tool_name VARCHAR(64) NOT NULL DEFAULT 'exec',
    command TEXT NOT NULL,
    working_dir VARCHAR(512) NOT NULL DEFAULT '/workspace',
    timeout_seconds INT NOT NULL DEFAULT 60,
    exit_code INT,
    status VARCHAR(32) NOT NULL DEFAULT 'RUNNING',
    error_code INT,
    error_message TEXT,
    stdout_excerpt TEXT,
    stderr_excerpt TEXT,
    duration_ms BIGINT,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    CONSTRAINT fk_sandbox_execution_session FOREIGN KEY (sandbox_session_id) REFERENCES sandbox_session (id),
    CONSTRAINT fk_sandbox_execution_conversation FOREIGN KEY (conversation_id) REFERENCES chat_conversation (id),
    CONSTRAINT fk_sandbox_execution_message FOREIGN KEY (message_id) REFERENCES chat_message (id)
);

CREATE INDEX idx_sandbox_execution_session
    ON sandbox_execution (sandbox_session_id, started_at);

CREATE INDEX idx_sandbox_execution_conversation
    ON sandbox_execution (conversation_id, started_at);

CREATE INDEX idx_sandbox_execution_tool_call
    ON sandbox_execution (tool_call_id);

CREATE TABLE sandbox_artifact (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sandbox_session_id BIGINT NOT NULL,
    execution_id BIGINT,
    conversation_id BIGINT NOT NULL,
    relative_path VARCHAR(512) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    size_bytes BIGINT NOT NULL DEFAULT 0,
    sha256 VARCHAR(64) NOT NULL,
    content_type VARCHAR(128) NOT NULL DEFAULT 'application/octet-stream',
    storage_bucket VARCHAR(128) NOT NULL,
    storage_key VARCHAR(1024) NOT NULL,
    version INT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sandbox_artifact_session FOREIGN KEY (sandbox_session_id) REFERENCES sandbox_session (id),
    CONSTRAINT fk_sandbox_artifact_execution FOREIGN KEY (execution_id) REFERENCES sandbox_execution (id),
    CONSTRAINT fk_sandbox_artifact_conversation FOREIGN KEY (conversation_id) REFERENCES chat_conversation (id),
    CONSTRAINT uk_sandbox_artifact_content UNIQUE (conversation_id, relative_path, sha256),
    CONSTRAINT uk_sandbox_artifact_object UNIQUE (storage_bucket, storage_key)
);

CREATE INDEX idx_sandbox_artifact_session
    ON sandbox_artifact (sandbox_session_id, created_at);

CREATE INDEX idx_sandbox_artifact_conversation_path
    ON sandbox_artifact (conversation_id, relative_path);
