INSERT INTO sys_role_menu (role_id, menu_id, created_by, updated_by)
SELECT sr.id, sm.id, 1, 1
FROM sys_role sr
JOIN (
    SELECT menu.id
    FROM sys_menu menu
    WHERE menu.name = 'skills'
    UNION ALL
    SELECT button.id
    FROM sys_menu menu
    JOIN sys_menu button ON button.parent_id = menu.id
    WHERE menu.name = 'skills'
        AND button.name IN ('skillUpload', 'skillDelete')
    UNION ALL
    SELECT button.id
    FROM sys_menu menu
    JOIN sys_menu button ON button.parent_id = menu.id
    WHERE menu.name = 'agentList'
        AND button.name = 'agentSkillUpdate'
) sm ON 1 = 1
WHERE sr.code = 'ADMIN'
    AND NOT EXISTS (
        SELECT 1
        FROM sys_role_menu srm
        WHERE srm.role_id = sr.id
            AND srm.menu_id = sm.id
    );
